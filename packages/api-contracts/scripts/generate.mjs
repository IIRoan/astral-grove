import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';
const root = resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const document = JSON.parse(readFileSync(resolve(root, 'openapi.json'), 'utf8'));
const schemas = document.components.schemas;
// Request schemas (`XInput`) accept defaulted fields as optional, so defaults must not imply required.
const types = astToString(await openapiTS(document, { defaultNonNullable: false }));
// Every Rust-validated schema `X` is emitted with an `XInput` twin; each pair gets output and input assertions.
const names = Object.keys(schemas).filter((name) => `${name}Input` in schemas);
const alignment = `// Generated by packages/api-contracts/scripts/generate.mjs from openapi.json; do not edit.
import type { components } from '@riftbound/api-contracts';
import type { z } from 'zod';
import type * as C from './index.js';
type Assert<T extends true> = T;
type S = components['schemas'];
// JSON omits undefined properties; Zod includes undefined explicitly on optional keys.
type FromWire<T> = T extends readonly (infer U)[]
  ? FromWire<U>[]
  : T extends object
    ? string extends keyof T
      ? { [K in keyof T]: FromWire<T[K]> }
      : {
          [K in keyof T]: Pick<T, K> extends Required<Pick<T, K>>
            ? FromWire<T[K]>
            : FromWire<T[K]> | undefined;
        }
    : T;
type IsUnion<T, U = T> = T extends unknown ? ([U] extends [T] ? false : true) : never;
// Assignability ignores optional keys present on one side only, so key sets are compared too (unions are skipped).
type KeyDrift<A, B> = [NonNullable<A>] extends [readonly (infer U)[]]
  ? [NonNullable<B>] extends [readonly (infer V)[]]
    ? KeyDrift<U, V>
    : never
  : [NonNullable<A>, NonNullable<B>] extends [object, object]
    ? true extends IsUnion<NonNullable<A>> | IsUnion<NonNullable<B>>
      ? never
      : string extends keyof NonNullable<A>
        ? never
        :
            | Exclude<keyof NonNullable<A>, keyof NonNullable<B>>
            | Exclude<keyof NonNullable<B>, keyof NonNullable<A>>
            | {
                [K in keyof NonNullable<A> &
                  keyof NonNullable<B>]: \`\${K & string}.\${KeyDrift<NonNullable<A>[K], NonNullable<B>[K]> & string}\`;
              }[keyof NonNullable<A> & keyof NonNullable<B>]
    : never;
type Matches<A, B> = [A] extends [FromWire<B>]
  ? [FromWire<B>] extends [A]
    ? [KeyDrift<A, B>] extends [never]
      ? true
      : { drift: KeyDrift<A, B> }
    : false
  : false;
${names
  .map(
    (name) => `export type ${name}Alignment = Assert<Matches<z.output<typeof C.${name}>, S['${name}']>>;
export type ${name}InputAlignment = Assert<Matches<z.input<typeof C.${name}>, S['${name}Input']>>;`
  )
  .join('\n')}
`;
const outputs = [
  [resolve(root, 'src/generated/schema.ts'), types],
  [resolve(root, '../contracts/src/rust-type-alignment.ts'), alignment],
];
for (const [destination, source] of outputs) {
  const output = await format(source, {
    ...(await resolveConfig(destination)),
    filepath: destination,
  });
  if (!check) writeFileSync(destination, output);
  else if (readFileSync(destination, 'utf8') !== output)
    throw new Error(`Generated ${destination} is stale; run cargo xtask openapi`);
}
if (!check)
  writeFileSync(
    resolve(root, 'openapi.json'),
    await format(JSON.stringify(document), {
      ...(await resolveConfig(resolve(root, 'openapi.json'))),
      parser: 'json',
    })
  );
console.log(`Rust OpenAPI / TypeScript contracts ${check ? 'verified' : 'generated'}`);
